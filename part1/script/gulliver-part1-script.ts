const stamp = '2026-11-14T00:00:00.000Z';
const VERSION = 'script-v1';
async function native(kind: string, id: string, name: string, content: unknown) {
  const artifact: Artifact<unknown> = {
    schemaVersion: 1,
    id,
    name,
    kind,
    provenance: { source: 'created' },
    draft: { baseVersionId: VERSION, updatedAt: stamp, content: structuredClone(content) },
    versions: [
      {
        artifactId: id,
        versionId: VERSION,
        parentVersionId: null,
        schemaVersion: 1,
        createdAt: stamp,
        createdBy: null,
        reason: 'ガリヴァー旅行記 第1部の脚本（fiction-manga@1.1.0 脚本、草案）',
        content,
        contentHash: await contentHash(content),
      },
    ],
  };
  return artifact;
}

const KIND_NAME = { N: 'ナレーション', D: '台詞', T: 'ト書き', S: '擬音' } as const;

function scriptDocument() {
  const blocks: DocumentBlock[] = [];
  let n = 0;
  const id = () => `s1-${String(++n).padStart(4, '0')}`;
  const h = (level: number, text: string) =>
    blocks.push({ ...createDocument().blocks[0], id: id(), type: 'heading', level, text });
  const p = (text: string) => blocks.push({ ...createDocument().blocks[1], id: id(), type: 'paragraph', text });
  h(1, 'ガリヴァー旅行記 第1部 脚本（1〜6話、草案）');
  p(
    '原文（Project Gutenberg #829 第1篇）から新しく訳した草案。台詞の決定は作者。書式：ナレーションは【N】（ガリヴァーの手記、明朝体）、台詞は「名前（CH）」、ト書きは（ ）、擬音は〔 〕（手書き、LY-08）。各話16ページ、横書き、左から右へ読む。',
  );
  for (const ep of PART1_SCRIPT) {
    const meta = EPISODES.find((e) => e.n === ep.n)!;
    h(2, `第${ep.n}話「${meta.title}」`);
    for (const s of ep.scenes) {
      const label = meta.scenes.find((x) => x.id === s.scene)!.label;
      h(3, `${s.scene} ${label}（${s.pages}ページ）`);
      for (const l of s.lines)
        p(
          l.k === 'N'
            ? `【N】${l.text}`
            : l.k === 'D'
              ? `${SPEAKER_NAMES[l.who!]}（${l.who}）「${l.text}」`
              : l.k === 'T'
                ? `（${l.text}）`
                : `〔${l.text}〕`,
        );
    }
  }
  return { ...createDocument(), blocks };
}

function scriptLines(): StructuredData {
  const rows: StructuredData['rows'] = [];
  for (const ep of PART1_SCRIPT)
    for (const s of ep.scenes)
      s.lines.forEach((l, i) =>
        rows.push({
          id: `${s.scene}.L${String(i + 1).padStart(2, '0')}`,
          values: {
            'ln.episode': `第${ep.n}話`,
            'ln.scene': s.scene,
            'ln.kind': KIND_NAME[l.k],
            'ln.speaker': l.who ?? '',
            'ln.text': l.text,
          },
        }),
      );
  return {
    schemaVersion: 2,
    columns: [
      { id: 'ln.episode', name: '話', type: 'text', required: true },
      { id: 'ln.scene', name: 'シーン', type: 'text', required: true },
      { id: 'ln.kind', name: '種類', type: 'select', options: Object.values(KIND_NAME), required: true },
      { id: 'ln.speaker', name: '話す人物', type: 'text' },
      { id: 'ln.text', name: '文', type: 'text', required: true },
    ],
    rows,
  };
}

export async function buildGulliverPart1Script() {
  return [
    await native('document', 'gm1-script', '第1部 脚本（1〜6話、草案）', scriptDocument()),
    await native('data', 'gm1-script-lines', '第1部 台詞とナレーションの表', scriptLines()),
  ];
}
